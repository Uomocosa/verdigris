type StaticSources<'w, 's, 'definition, 'owner, 'zone, 'enchanting> = Query<
    'w,
    's,
    (
        Entity,
        &'definition cards::CardDefinition,
        &'owner cards::Owner,
        &'zone zones::InZone,
        Option<&'enchanting cards::Enchanting>,
    ),
>;

type StaticCandidates<'w, 's, 'definition, 'owner, 'zone, 'attacking, 'token> = Query<
    'w,
    's,
    (
        Entity,
        &'definition cards::CardDefinition,
        &'owner cards::Owner,
        &'zone zones::InZone,
        Option<&'attacking cards::Attacking>,
        Option<&'token cards::Token>,
    ),
>;

/// 611.3a A continuous effect generated by a static ability isn’t “locked in”; it applies at any given moment to whatever its text indicates.
///
/// # See also
///
/// 611.3. A continuous effect may be generated by the static ability of an object.
///
/// 611.3b The effect applies at all times that the permanent generating it is on the battlefield or the object generating it is in the appropriate zone.
pub fn r611_3a_static_effects(
    mut commands: Commands,
    sources: StaticSources<'_, '_, '_, '_, '_, '_>,
    candidates: StaticCandidates<'_, '_, '_, '_, '_, '_, '_>,
    stamped: Query<&effects::SourceTimestamp>,
    applied: Query<(Entity, &effects::ContinuousEffect)>,
    players: Res<turns::TurnOrder>,
    zones: zones::ZoneLookup,
    mut timestamp: ResMut<effects::Timestamp>,
) {
    let players = players.into_inner();
    let players: Vec<players::PlayerId> = players.iter().copied().collect();
    for (entity, effect) in applied.iter() {
        if effect.until != effects::Duration::WhileSourceOnBattlefield {
            continue;
        }
        let Some(source) = effect.source else {
            continue;
        };
        let Ok((_, source_definition, source_owner, source_zone, enchanting)) = sources.get(source)
        else {
            commands.entity(entity).despawn();
            continue;
        };
        let enchanted = enchanting.map(|entity| **entity);
        if !zones.contains(BATTLEFIELD, **source_zone) {
            commands.entity(entity).despawn();
            continue;
        }
        let still_applies = source_definition.continuous_abilities().any(|ability| {
            ability_still_applies(
                ability,
                effect,
                source,
                enchanted,
                **source_owner,
                &candidates,
                &zones,
                &players,
            )
        });
        if !still_applies {
            commands.entity(entity).despawn();
        }
    }
    for (source, definition, owner, in_zone, enchanting) in sources.iter() {
        let enchanted = enchanting.map(|entity| **entity);
        if definition.continuous_abilities().next().is_none() {
            continue;
        }
        if !zones.contains(BATTLEFIELD, **in_zone) {
            continue;
        }
        let stamp = stamp_for(source, &mut commands, &stamped, &mut timestamp);
        for ability in definition.continuous_abilities() {
            match ability.filter.kind {
                effects::FilterKind::Creature => spawn_creature_effects(
                    &mut commands,
                    source,
                    ability,
                    enchanted,
                    **owner,
                    &candidates,
                    &zones,
                    &players,
                    &applied,
                    stamp,
                ),
                effects::FilterKind::Player => spawn_player_effects(
                    &mut commands,
                    source,
                    ability,
                    enchanted,
                    **owner,
                    &players,
                    &applied,
                    stamp,
                ),
                _ => {}
            }
        }
    }
}

fn ability_still_applies(
    ability: &abilities::Continuous,
    effect: &effects::ContinuousEffect,
    source: Entity,
    enchanted: Option<Entity>,
    controller: players::PlayerId,
    candidates: &StaticCandidates<'_, '_, '_, '_, '_, '_, '_>,
    zones: &zones::ZoneLookup,
    players: &[players::PlayerId],
) -> bool {
    if ability.modification != effect.modification {
        return false;
    }
    match ability.filter.kind {
        effects::FilterKind::Creature => candidates.get(effect.affected).is_ok_and(
            |(_, definition, owner, zone, attacking, token)| {
                zones.contains(BATTLEFIELD, **zone)
                    && candidate_matches(
                        ability.filter,
                        source,
                        effect.affected,
                        enchanted,
                        controller,
                        **owner,
                        attacking.is_some(),
                        token.is_some(),
                        definition,
                        players,
                    )
            },
        ),
        effects::FilterKind::Player => player_matches(
            ability.filter,
            source,
            players::PlayerId(effect.affected),
            enchanted,
            controller,
            players,
        ),
        _ => false,
    }
}

fn spawn_creature_effects(
    commands: &mut Commands,
    source: Entity,
    ability: &abilities::Continuous,
    enchanted: Option<Entity>,
    controller: players::PlayerId,
    candidates: &StaticCandidates<'_, '_, '_, '_, '_, '_, '_>,
    zones: &zones::ZoneLookup,
    players: &[players::PlayerId],
    applied: &Query<(Entity, &effects::ContinuousEffect)>,
    stamp: u64,
) {
    for (candidate, definition, owner, zone, attacking, token) in candidates.iter() {
        if !zones.contains(BATTLEFIELD, **zone) {
            continue;
        }
        if !candidate_matches(
            ability.filter,
            source,
            candidate,
            enchanted,
            controller,
            **owner,
            attacking.is_some(),
            token.is_some(),
            definition,
            players,
        ) {
            continue;
        }
        if already_applied(applied, source, candidate, &ability.modification) {
            continue;
        }
        commands.spawn(effects::ContinuousEffect {
            affected: candidate,
            source: Some(source),
            modification: ability.modification.clone(),
            until: effects::Duration::WhileSourceOnBattlefield,
            timestamp: stamp,
        });
    }
}

fn spawn_player_effects(
    commands: &mut Commands,
    source: Entity,
    ability: &abilities::Continuous,
    enchanted: Option<Entity>,
    controller: players::PlayerId,
    players: &[players::PlayerId],
    applied: &Query<(Entity, &effects::ContinuousEffect)>,
    stamp: u64,
) {
    for candidate in players {
        if !player_matches(
            ability.filter,
            source,
            *candidate,
            enchanted,
            controller,
            players,
        ) {
            continue;
        }
        if already_applied(applied, source, **candidate, &ability.modification) {
            continue;
        }
        commands.spawn(effects::ContinuousEffect {
            affected: **candidate,
            source: Some(source),
            modification: ability.modification.clone(),
            until: effects::Duration::WhileSourceOnBattlefield,
            timestamp: stamp,
        });
    }
}

fn stamp_for(
    source: Entity,
    commands: &mut Commands,
    stamped: &Query<&effects::SourceTimestamp>,
    timestamp: &mut ResMut<effects::Timestamp>,
) -> u64 {
    stamped.get(source).map_or_else(
        |_| {
            let next = timestamp.advance();
            commands.entity(source).insert(effects::SourceTimestamp(next));
            next
        },
        |existing| **existing,
    )
}

fn candidate_matches(
    filter: effects::Filter,
    source: Entity,
    candidate: Entity,
    enchanted: Option<Entity>,
    controller: players::PlayerId,
    candidate_owner: players::PlayerId,
    is_attacking: bool,
    is_token: bool,
    definition: &cards::CardDefinition,
    players: &[players::PlayerId],
) -> bool {
    match filter.object {
        Some(effects::ObjectRelation::ThisObject) if candidate != source => return false,
        Some(effects::ObjectRelation::EnchantedObject) if enchanted != Some(candidate) => {
            return false;
        }
        _ => {}
    }
    if let Some(controller_ref) = filter.controlled_by
        && !controller_ref.resolve(controller, players).contains(&candidate_owner)
    {
        return false;
    }
    if filter.attacking && !is_attacking {
        return false;
    }
    if filter.nontoken && is_token {
        return false;
    }
    filter.does_creature_match(definition)
}

fn player_matches(
    filter: effects::Filter,
    source: Entity,
    candidate: players::PlayerId,
    enchanted: Option<Entity>,
    controller: players::PlayerId,
    players: &[players::PlayerId],
) -> bool {
    match filter.object {
        Some(effects::ObjectRelation::ThisObject) if *candidate != source => return false,
        Some(effects::ObjectRelation::EnchantedObject) if enchanted != Some(*candidate) => {
            return false;
        }
        _ => {}
    }
    filter.controlled_by.map_or_else(
        || players.contains(&candidate),
        |controller_ref| controller_ref.resolve(controller, players).contains(&candidate),
    )
}

fn already_applied(
    applied: &Query<(Entity, &effects::ContinuousEffect)>,
    source: Entity,
    affected: Entity,
    modification: &effects::Modification,
) -> bool {
    applied.iter().any(|(_, effect)| {
        effect.source == Some(source)
            && effect.affected == affected
            && &effect.modification == modification
            && effect.until == effects::Duration::WhileSourceOnBattlefield
    })
}

